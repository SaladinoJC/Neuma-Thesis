"""Export the editable Music Garden clearing as an Android VectorDrawable.

The master uses only filled paths. Colours come from design-tokens.json; no
musical notation is encoded in this decorative asset. Run from any directory.
"""
from pathlib import Path
import xml.etree.ElementTree as ET
import json


def main():
    root = Path(__file__).resolve().parents[1]
    source = root / "assets/source/interiors/vocal-clearing.svg"
    destination = root / "Plataforma/app/src/main/res/drawable/garden_vocal_clearing.xml"
    colours = json.loads((root / "design-tokens.json").read_text(encoding="utf-8"))["color"]
    svg = ET.parse(source).getroot()
    paths = list(svg.findall("{http://www.w3.org/2000/svg}path"))
    if svg.get("viewBox") != "0 0 768 512" or not paths:
        raise ValueError("Unexpected master viewport or empty drawing")
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/prepare_vocal_clearing.py; edit the SVG master. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="192dp" android:height="128dp"',
             '    android:viewportWidth="768" android:viewportHeight="512">']
    for path in paths:
        colour = colours[path.attrib["data-token"]]
        if path.get("fill") != colour:
            raise ValueError("Master colour differs from tokens: " + path.attrib["data-token"])
        lines.append(f'    <path android:fillColor="{colour}" android:pathData="{path.attrib["d"]}" />')
    lines.append("</vector>")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {destination.relative_to(root)} ({len(paths)} paths)")


if __name__ == "__main__":
    main()
