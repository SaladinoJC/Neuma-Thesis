"""Generate the scoped Compose palettes; no changes to Garden's token generator."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / 'Plataforma/app/src/main/java/ar/edu/unmdp/entrenamiento/ui'
tokens = json.loads((ROOT / 'design-tokens.json').read_text(encoding='utf-8'))
quiet = tokens['quietStudio']['color']
header = '// Generated by tools/prepare_quiet_tokens.py from design-tokens.json\n'
header += 'package ar.edu.unmdp.entrenamiento.ui\n\n'
header += 'import androidx.compose.ui.graphics.Color\n\n'
header += 'import androidx.compose.ui.unit.dp\n\n'
fields = {key[0].upper() + key[1:]: value for key, value in quiet.items()}
source = header + 'internal object QuietTokens {\n'
for key, value in fields.items():
    source += f'    val {key} = Color(0xFF{value[1:]})\n'
for key, value in tokens['quietStudio']['touch'].items():
    source += f'    val {key[0].upper() + key[1:]} = {value}.dp\n'
source += '}\n'
(UI / 'QuietTokens.kt').write_text(source, encoding='utf-8')
source = header + 'import ar.edu.unmdp.entrenamiento.BuildConfig\n\ninternal object RhythmTokens {\n'
for key in fields:
    source += f'    val {key} = if (BuildConfig.QUIET_STUDIO) QuietTokens.{key} else GardenTokens.{key}\n'
for key in ['SpaceXs', 'SpaceSm', 'SpaceMd', 'SpaceBase', 'SpaceLg', 'SpaceXl', 'TouchMinimum', 'RadiusLarge']:
    source += f'    val {key} = GardenTokens.{key}\n'
source += '}\n'
(UI / 'RhythmTokens.kt').write_text(source, encoding='utf-8')
